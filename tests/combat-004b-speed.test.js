"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"..","battle-speed.js"),"utf8");
const speed=vm.runInNewContext(source+"\nBattleSpeed");
assert.deepEqual(Array.from(speed.levels),[1,2,4]);
assert.equal(speed.get(),1);
assert.equal(speed.multiplier(),1);
assert.equal(speed.duration(350),350);
assert.equal(speed.set(2),true);
assert.equal(speed.duration(350),175);
assert.equal(speed.duration(1000),500,"animation duration can use the same scaling");
assert.equal(speed.multiplier(),2,"visual animation rate uses the shared multiplier");
assert.equal(speed.next(),4);
assert.equal(speed.duration(350),88);
assert.equal(speed.duration(250),63);
assert.equal(speed.next(),1);
assert.equal(speed.set(3),false);
assert.equal(speed.get(),1,"invalid speed must leave current state untouched");
for(const input of [-1,Infinity,NaN])assert.throws(()=>speed.duration(input));
assert.equal(speed.duration(0),0);
assert.equal(speed.set(4),true);
assert.equal(speed.duration(1),1,"nonzero presentation times never disappear");
assert.equal(speed.reset(),1);
assert.equal(speed.multiplier(),1);
console.log("Combat-004B shared speed: delays, playback multiplier, resets and invalid values passed");
