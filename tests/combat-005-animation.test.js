"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.join(__dirname,"..");
const api=vm.runInNewContext(["battle-speed.js","battle-animation.js"].map(n=>fs.readFileSync(path.join(root,n),"utf8")).join("\n")+"\n({BattleSpeed,BattleAnimation})");
const {BattleSpeed:speed,BattleAnimation:motion}=api;
const hit=(actorId,targetId)=>[{type:"ability",actorId,targetId,abilityId:"basic"},{type:"damage",actorId,targetId,amount:10}];
const guard=[{type:"ability",actorId:"a",targetId:"a",abilityId:"special"},{type:"effect",actorId:"a",targetId:"a",effect:"guard"}];
motion.enqueue(guard);
assert.equal(motion.pending(),0,"support abilities never lunge at allies");
motion.enqueue(hit("hero","enemy"));
motion.enqueue(hit("enemy","hero"));
assert.equal(motion.pending(),2);
motion.tick(50,speed.multiplier());
assert.ok(motion.pose("hero")>0);
assert.ok(motion.pose("enemy")<0);
motion.tick(50,speed.multiplier());
const at100=motion.pose("hero");
assert.ok(at100>0);
motion.clear();
assert.equal(motion.pending(),0);
assert.equal(motion.pose("hero"),0);
motion.enqueue(hit("hero","enemy"));
speed.set(4);
motion.tick(25,speed.multiplier());
assert.equal(motion.pose("hero"),at100,"same progress when elapsed scaled to 100ms");
motion.tick(45,speed.multiplier());
assert.equal(motion.pending(),0,"4x animation finishes in 70ms");
assert.equal(motion.pose("hero"),0);
speed.reset();
motion.enqueue(hit("hero","enemy"));
motion.tick(70,speed.multiplier());
assert.equal(motion.pending(),1,"1x animation is slower");
assert.ok(motion.pose("hero")>0);
motion.clear();
motion.enqueue(hit("hero","enemy"));
motion.tick(10,NaN);
assert.equal(motion.pending(),1);
assert.equal(motion.pose("hero"),0);
motion.tick(-10,1);
assert.equal(motion.pose("hero"),0);
motion.clear();
assert.equal(motion.pending(),0,"battle exit or reset must clear animations");
console.log("Combat-005 animation: attacks only, speed scaling, queue, cancel and reset passed");
