"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.join(__dirname,"..");
const source=["initiative-model.js","ability-data.js","combat-core.js","combat-log.js","progress-core.js","save-core.js","animation-profiles.js","battle-animation.js"]
 .map(name=>fs.readFileSync(path.join(root,name),"utf8")).join("\n");
const {CombatCore,AbilityData,CombatLog,SaveCore,ProgressCore,BattleAnimation}=vm.runInNewContext(source+"\n({CombatCore,AbilityData,CombatLog,SaveCore,ProgressCore,BattleAnimation})");
const hero=(id,side="ally",hp=100,atk=15,speed=150)=>({id,side,hp,atk,speed,name:id});
function battle(){
 const b=CombatCore.createBattle([hero("medic-demo"),hero("kael"),hero("enemy","enemy",300,2,5)]);
 CombatCore.advanceToPlayerTurn(b);
 return b;
}
assert.equal(AbilityData.get(hero("medic-demo"),"special").kind,"heal");
const b=battle();
b.fighters[1].hp=25;
assert.equal(CombatCore.chooseAlly(b,1),true);
assert.equal(CombatCore.performPlayerAbility(b,"special"),true);
assert.equal(b.fighters[1].hp,55);
assert.equal(b.fighters[0].specialCooldown,2);
assert.ok(b.events.some(e=>e.type==="heal"&&e.amount===30&&e.remainingHp===55));
assert.match(CombatLog.lines(b.events,b.fighters).join(" | "),/\+30 HP/);
BattleAnimation.clear();
BattleAnimation.enqueue(b.events);
assert.ok(BattleAnimation.pending()>=2,"healing uses supporter and recipient visuals");
const full=battle();
assert.equal(CombatCore.performPlayerAbility(full,"special"),true);
assert.equal(full.fighters[0].hp,100,"cannot overheal");
const near=battle();
near.fighters[1].hp=97;
CombatCore.chooseAlly(near,1);
CombatCore.performPlayerAbility(near,"special");
assert.equal(near.fighters[1].hp,100);
const invalid=battle();
invalid.selectedAlly=2;
assert.equal(CombatCore.performPlayerAbility(invalid,"special"),false);
assert.equal(invalid.fighters[0].specialCooldown,0);
assert.equal(invalid.allyActions,0);
const dead=battle();
dead.fighters[1].hp=0;
assert.equal(CombatCore.chooseAlly(dead,1),false);
dead.selectedAlly=1;
assert.equal(CombatCore.performPlayerAbility(dead,"special"),false);
const oldHeroes=[hero("kael"),hero("lyra"),hero("darin")];
const newHeroes=[...oldHeroes,hero("medic-demo")];
const old={version:1,materials:7,levels:{kael:3,lyra:2,darin:1}};
assert.equal(SaveCore.validate(old,newHeroes),null,"old demo saves are intentionally not migrated");
const fresh={version:2,accountXp:180,currency:7,levels:{kael:3,lyra:2,darin:1},claimedMissions:[]};
const restored=SaveCore.validate(fresh,newHeroes);
assert.equal(restored.currency,7);
assert.equal(restored.levels.kael,3);
assert.equal(restored.levels.lyra,2);
assert.equal(restored.levels["medic-demo"],1);
assert.equal(SaveCore.validate({...fresh,levels:{...fresh.levels,unknown:1}},newHeroes),null);
console.log("Combat-007 healing, log, visuals and old-save migration passed");
