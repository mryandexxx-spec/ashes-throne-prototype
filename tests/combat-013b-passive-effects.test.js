"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const src=["initiative-model.js","ability-data.js","combat-core.js","combat-log.js"]
 .map(n=>fs.readFileSync(path.join(__dirname,"..",n),"utf8")).join("\n");
const {CombatCore:core,AbilityData}=vm.runInNewContext(src+"\n({CombatCore,AbilityData})");
const ally=(id,hp=100,atk=20,speed=300)=>({id,name:id,side:"ally",hp,atk,speed});
const foe=(id="foe",hp=500,atk=1,speed=1)=>({id,name:id,side:"enemy",hp,atk,speed});
const battle=(heroes,enemies=[foe()],waves=[])=>{
 const b=core.createBattle([...heroes,...enemies],waves);
 core.advanceToPlayerTurn(b);
 return b;
};
const events=(b,type)=>Array.from(b.events).filter(x=>x.type===type);

// A permanent passive changes the computed attack but not the base stat.
let b=battle([ally("test-passive-always")]);
assert.equal(core.effectiveStat(b,b.fighters[0],"atk"),25);
assert.equal(b.fighters[0].atk,20);
const first=b.fighters.find(x=>x.id==="foe"),before=first.hp;
assert.equal(core.performPlayerAbility(b,"basic"),true);
assert.equal(first.hp,before-25,"permanent attack modifier affects actual damage");
assert.equal(b.fighters[0].atk,20,"base stats never drift");
assert.equal(b.allyActions,1);

// A conditional modifier is sampled at the moment of the hit, not when the
// battle starts or the action is registered.
b=battle([ally("test-passive-conditional")]);
const owner=b.fighters[0],target=b.fighters[1];
assert.equal(core.effectiveStat(b,owner,"atk"),20);
owner.hp=49;
assert.equal(core.effectiveStat(b,owner,"atk"),27);
const hpBefore=target.hp;
assert.equal(core.performPlayerAbility(b,"basic"),true);
assert.equal(target.hp,hpBefore-27);
owner.hp=80;
assert.equal(core.effectiveStat(b,owner,"atk"),20,
 "healing immediately deactivates conditional passive");
assert.equal(owner.atk,20);

// More than one flat modifier adds deterministically, in definition order.
b=battle([ally("test-passive-combined")]);
assert.equal(core.effectiveStat(b,b.fighters[0],"atk"),23);
b.fighters[0].hp=49;
assert.equal(core.effectiveStat(b,b.fighters[0],"atk"),30);
assert.equal(b.fighters[0].atk,20);

// Derived speed influences initiative without editing the displayed base
// speed or making the classic InitiativeModel path incompatible.
b=battle([ally("kael",100,20,120),ally("test-passive-speed",100,20,100)]);
assert.equal(b.fighters[b.currentActor].id,"test-passive-speed",
 "a passive speed bonus changes who becomes ready first");
assert.equal(core.effectiveStat(b,b.fighters[1],"speed"),150);
assert.equal(b.fighters[1].speed,100,"base speed is unchanged");

// Reaction effects require no manual action and do not feed back into the
// trigger dispatcher, including heal events generated by the passive itself.
b=core.createBattle([ally("test-passive-healer",100,20,50),foe("attacker",500,1,250)]);
const healer=b.fighters[0];
core.advanceToPlayerTurn(b);
const ts=Array.from(b.events).filter(x=>x.type==="passive-trigger");
const heals=Array.from(b.events).filter(x=>x.type==="heal"&&x.passiveId==="passive");
assert.ok(ts.length>0,"AI damage triggers reactions automatically");
assert.equal(heals.length,ts.length,
 "each matching source event creates exactly one healing reaction");
assert.ok(heals.every(x=>x.actorId==="test-passive-healer"&&x.targetId===x.actorId));
assert.equal(healer.hp,100,"healing is capped at max HP");
assert.equal(b.allyActions,0,"passive reactions do not spend actions");
assert.equal(b.turn,1+Array.from(b.events).filter(x=>x.type==="ability").length,
 "reaction never advances the initiative turn");
assert.ok(!ts.some(x=>x.sourceEventType==="heal"),
 "generated heal never triggers a recursive dispatch");

// Dead owners cannot receive healing from their own hit reaction.
b=core.createBattle([ally("test-passive-healer",1,20,50),foe("executioner",500,20,250)]);
core.advanceToPlayerTurn(b);
assert.equal(b.winner,"enemy");
assert.equal(b.fighters[0].hp,0);
assert.equal(Array.from(b.events).filter(x=>x.type==="passive-trigger").length,0);

// All playable heroes retain their exact base stats and empty passives.
for(const id of ["kael","lyra","darin","medic-demo","test-area-damage"]){
 b=battle([ally(id)]);
 const a=b.fighters[0];
 assert.equal(core.effectiveStat(b,a,"atk"),a.atk);
 assert.equal(core.effectiveStat(b,a,"speed"),a.speed);
 const p=AbilityData.get(a,"passive");
 assert.equal(p.modifiers.length,0);
 assert.equal(p.triggers.length,0);
 assert.equal(AbilityData.get(a,"leader"),null);
}
const fresh=battle([ally("test-passive-conditional")]);
assert.equal(core.effectiveStat(fresh,fresh.fighters[0],"atk"),20,
 "new battle clears conditional state");
console.log("Combat-013B permanent/conditional attack, derived speed, nonrecursive healing, death and reset passed");
