"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=["progress-core.js","save-core.js"].map(file=>fs.readFileSync(path.join(__dirname,"..",file),"utf8")).join("\n");
const {ProgressCore:P,SaveCore:S}=vm.runInNewContext(source+"\n({ProgressCore,SaveCore})");
const hero={id:"kael",side:"ally"};
const p=P.createProgress([hero]);
p.energy.value=0;
p.energy.updatedAt=1000;
p.currency=0;
p.gearMaterials=0;
p.accountXp=75;
const originalGear=JSON.stringify(p.gear);
const first=P.grantTestResources(p,100000);
assert.deepEqual([first.currency,first.material,first.energy],[5000,100,240]);
assert.equal(p.energy.value,240);
assert.equal(p.energy.updatedAt,100000);
assert.equal(p.currency,5000);
assert.equal(p.gearMaterials,100);
assert.equal(p.accountXp,75);
assert.equal(JSON.stringify(p.gear),originalGear);
assert.equal(P.grantTestResources(p,100001).currency,0,"repeat is stable");
assert.equal(p.currency,5000);
assert.equal(p.gearMaterials,100);
p.currency=7500;p.gearMaterials=210;p.energy.value=100;
assert.deepEqual(Object.values(P.grantTestResources(p,100002)),[0,0,140]);
assert.equal(p.currency,7500,"higher balance cannot drop");
assert.equal(p.gearMaterials,210,"higher balance cannot drop");
assert.equal(p.energy.value,240);
assert.equal(P.grantTestResources(p,-1),null);
const storage=new Map(),adapter={getItem:key=>storage.get(key)??null,setItem:(key,v)=>storage.set(key,v)};
assert.equal(S.save(p,()=>adapter),true);
const loaded=S.load([hero],()=>adapter);
assert.equal(loaded.fresh,false);
assert.equal(loaded.progress.currency,7500);
assert.equal(loaded.progress.gearMaterials,210);
assert.equal(loaded.progress.energy.value,240);
assert.equal(loaded.progress.accountXp,75);
console.log("DEV-RES-001 prototype resource refill, safe repeat, no progression mutation and v2 save passed");
