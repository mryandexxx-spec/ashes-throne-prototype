"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const scripts=["gear-data.js","progress-core.js","skill-core.js","hero-collection-core.js","daily-core.js","login-core.js","progress-v3-core.js","save-core.js","mission-data.js","campaign-core.js"];
const api=vm.runInNewContext(scripts.map(read).join("\n")+"\n({HeroCollectionCore,SaveCore,ProgressV3Core,MissionData,CampaignCore})");
const {HeroCollectionCore:H,SaveCore,ProgressV3Core:V,MissionData,CampaignCore}=api;
const allies=H.IDS.map(id=>({id,side:"ally"}));
const db=new Map(),get=()=>({getItem:key=>db.get(key)??null,setItem:(key,val)=>db.set(key,val)});
const fresh=SaveCore.load(allies,get);
assert.equal(fresh.progress.saveVersion,3);
assert.deepEqual(Array.from(fresh.progress.unlockedHeroes),["kael","lyra","darin","ren"]);
assert.deepEqual(Array.from(H.IDS.filter(id=>H.owned(fresh.progress,id))),["kael","lyra","darin","ren"]);
assert.equal(H.owned(fresh.progress,"medic-demo"),false);
assert.equal(H.owned(fresh.progress,"test-area-damage"),false);
assert.equal(H.owned(fresh.progress,"ves"),false);
assert.equal(H.reward("black-pass-ambush"),"medic-demo");
assert.equal(H.reward("demo-mission-2"),"test-area-damage");
assert.equal(H.reward("demo-mission-3"),null);
assert.ok(MissionData.get(H.unlockMission("medic-demo")));
assert.equal(H.grant(fresh.progress,"demo-mission-3"),null);
assert.equal(H.grant(fresh.progress,"black-pass-ambush"),"medic-demo");
assert.equal(H.grant(fresh.progress,"black-pass-ambush"),null,"no duplicate unlock");
assert.equal(H.owned(fresh.progress,"medic-demo"),true);
assert.equal(H.owned(fresh.progress,"test-area-damage"),false);
assert.equal(SaveCore.save(fresh.progress,get),true);
const reloaded=SaveCore.load(allies,get).progress;
assert.equal(H.owned(reloaded,"medic-demo"),true);
assert.equal(H.owned(reloaded,"test-area-damage"),false);
assert.equal(H.grant(reloaded,"demo-mission-2"),"test-area-damage");
assert.equal(SaveCore.save(reloaded,get),true);
assert.deepEqual(Array.from(SaveCore.load(allies,get).progress.unlockedHeroes).sort(),Array.from(H.IDS).sort());
const original=db.get(V.KEY);
const tampered=JSON.parse(original);tampered.unlockedHeroes=["kael","kael","darin"];
db.set(V.KEY,JSON.stringify(tampered));
assert.equal(SaveCore.load(allies,get).blocked,true,"corrupt roster must block save, not wipe it");
db.set(V.KEY,original);
const stale=JSON.parse(original);stale.revision=(stale.revision??0)+1;
db.set(V.KEY,JSON.stringify(stale));
assert.equal(SaveCore.save(reloaded,get),false,"concurrent save rejected");
db.set(V.KEY,original);
const legacy=JSON.parse(original);
delete legacy.unlockedHeroes;
db.set(V.KEY,JSON.stringify(legacy));
const oldProfile=SaveCore.load(allies,get).progress;
assert.equal(oldProfile.unlockedHeroes,undefined);
assert.equal(H.IDS.every(id=>H.owned(oldProfile,id)),true,"old local saves retain prior heroes and available Ren");
assert.equal(H.grant(oldProfile,"black-pass-ambush"),null);
assert.equal(SaveCore.save(oldProfile,get),true,"legacy v3 remains writable");
assert.equal(H.IDS.every(id=>H.owned(SaveCore.load(allies,get).progress,id)),true);
const html=read("index.html"),game=read("game.js"),css=read("styles.css");
assert.ok(html.includes('src="hero-collection-core.js"'));
assert.ok(html.indexOf('src="hero-collection-core.js"')<html.indexOf('src="progress-v3-core.js"'));
assert.ok(game.includes("function heroOwned(id)"));
assert.ok(game.includes("HeroCollectionCore.grant(progress,activeMissionId)"));
assert.ok(game.includes("if(!ALLIES.some(h=>h.id===id)||!heroOwned(id))return false;"));
assert.ok(game.includes(".filter(heroOwned)"));
assert.ok(game.includes('data-open-hero='));
assert.ok(game.includes('data-hero-id='));
assert.ok(css.includes(".hero-card.hero-locked"));
assert.equal(JSON.parse(read("package.json")).version,"0.3.92");
assert.ok(html.includes("v0.3.92 · UIHERO002"));
console.log("Heroes-001: new/legacy collection, mission grants, duplicate protection, squad gate and v3 storage passed");
