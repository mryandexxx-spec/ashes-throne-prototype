"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const D=vm.runInNewContext(read("daily-core.js")+"\nDailyCore");
const progress={saveVersion:3};
const day="2026-11-08";
assert.equal(D.unclaimedCount(progress,day),0);
assert.equal(progress.daily,undefined,"reading badge must not change an existing save");
assert.equal(D.today(progress,day),true);
assert.equal(D.record(progress,"hero-level",day),true);
assert.equal(D.unclaimedCount(progress,day),1);
assert.equal(D.record(progress,"equip-item",day),true);
assert.equal(D.record(progress,"campaign-battle",day),true);
assert.equal(D.unclaimedCount(progress,day),3);
progress.currency=1000;progress.accountXp=0;
progress.materials={Fe:0,Le:0,Cl:0,Wo:0,Fa:0,Th:0,Gl:0};
assert.ok(D.claim(progress,"hero-level",day));
assert.equal(D.unclaimedCount(progress,day),2);
assert.ok(D.claim(progress,"equip-item",day));
assert.ok(D.claim(progress,"campaign-battle",day));
assert.equal(D.unclaimedCount(progress,day),0);
assert.equal(D.unclaimedCount(progress,"2026-11-09"),0);
assert.equal(D.unclaimedCount(progress,"2026-11-07"),0,"rollback cannot display yesterday's rewards");
assert.equal(progress.daily.day,day,"checking badge across days is read-only");
const invalid={saveVersion:3,daily:{day,claimed:["hero-level","hero-level"],counts:progress.daily.counts}};
assert.equal(D.unclaimedCount(invalid,day),0,"invalid state must not display bogus claim count");
const html=read("index.html"),game=read("game.js"),styles=read("styles.css");
assert.match(html,/id="dailyClaimBadge"/);
assert.match(html,/id="dailyTasksNav"/);
assert.match(html,/v0\.3\.104 · RENGLB003/);
assert.match(styles,/\.daily-nav-badge\[hidden\]\{display:none\}/);
assert.ok(game.includes('DailyCore.unclaimedCount(progress,dailyDay())'));
assert.ok(game.includes('const LOGIN_CALENDAR_SEEN_KEY="ashes-throne.login-calendar-seen.v1"'));
assert.ok(game.includes('window.localStorage?.getItem(LOGIN_CALENDAR_SEEN_KEY)'));
assert.ok(game.includes('window.localStorage?.setItem(LOGIN_CALENDAR_SEEN_KEY,day)'));
assert.ok(game.includes('if(id==="loginCalendar"){\n  markLoginCalendarSeen();'));
assert.ok(game.includes('if(id==="home"){\n  renderDailyClaimBadge();\n  maybeOpenLoginOnEntry();'));
assert.ok(game.endsWith('maybeOpenLoginOnEntry();\n'));
assert.match(game,/if\(document\.hidden\|\|saveBlocked/);
assert.match(game,/showScreen\("loginCalendar"\);/);
console.log("Login-002: unclaimed daily badge count and once-per-day entry visibility wiring passed");
