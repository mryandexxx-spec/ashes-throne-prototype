"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const core=vm.runInNewContext(fs.readFileSync(path.join(__dirname,"..","progress-core.js"),"utf8")+"\nProgressCore");
const heroes=[
 {id:"kael",side:"ally",hp:120,atk:24,speed:110},
 {id:"lyra",side:"ally",hp:88,atk:31,speed:155},
 {id:"ves",side:"enemy",hp:90,atk:18,speed:105}
];
const p=core.createProgress(heroes);
assert.equal(p.accountXp,0);
assert.equal(p.currency,0);
assert.equal(p.levels.kael,1);
assert.equal(core.levelOf(p,"ves"),null);
assert.equal(core.accountLevel(p),1);
assert.equal(core.upgradeCost(p,"kael"),null,"account limit applies");
assert.equal(core.upgrade(p,"kael"),false);
assert.equal(core.claimFirstClear(p,"black-pass-ambush",{active:true,winner:"ally"}),null);
assert.equal(core.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"enemy"}),null);
const result=core.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"});
assert.equal(result.xp,80);
assert.equal(result.currency,500);
assert.equal(p.accountXp,80);
assert.equal(p.currency,500);
assert.equal(core.accountLevel(p),2);
assert.equal(core.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"}),null,"no duplicate first clear");
assert.equal(core.claimFirstClear(p,"missing",{active:false,winner:"ally"}),null);
assert.equal(core.upgradeCost(p,"kael"),39);
assert.equal(core.upgrade(p,"ves"),false,"enemies cannot upgrade");
assert.equal(core.upgrade(p,"kael"),true);
assert.equal(p.currency,461);
assert.equal(p.levels.kael,2);
assert.equal(core.heroStats(p,heroes[0]).hp,125);
assert.equal(core.heroStats(p,heroes[0]).atk,25);
assert.equal(core.heroStats(p,heroes[0]).speed,110,"speed never changes");
assert.equal(core.canUpgrade(p,"kael"),false,"account level blocks upgrade");
assert.equal(core.heroStats(p,heroes[1]).hp,88);
assert.equal(core.claimFirstClear(p,"demo-mission-2",{active:false,winner:"ally"}).xp,100);
assert.equal(core.accountLevel(p),4);
assert.equal(core.upgrade(p,"kael"),true);
assert.equal(core.upgrade(p,"kael"),true);
assert.equal(core.levelOf(p,"kael"),4);
assert.equal(core.upgrade(p,"kael"),false,"account cap still applies");
p.accountXp=1000000;p.currency=100000;
while(core.canUpgrade(p,"kael"))assert.equal(core.upgrade(p,"kael"),true);
assert.equal(core.levelOf(p,"kael"),15,"slice hero cap");
assert.equal(core.accountLevel(p),15,"slice account cap");
assert.equal(core.upgradeCost(p,"kael"),null);
assert.equal(heroes[0].hp,120,"base data immutable");
console.log("Progress VS-001A account XP, first clears, currency costs and caps passed");
