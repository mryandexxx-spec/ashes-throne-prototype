"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=["progress-core.js","save-core.js"].map(p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8")).join("\n");
const {ProgressCore:P,SaveCore:S}=vm.runInNewContext(source+"\n({ProgressCore,SaveCore})");
const hero={id:"kael",side:"ally",hp:120,atk:24,speed:110};
const foe={id:"enemy",side:"enemy",hp:90,atk:18,speed:99};
const p=P.createProgress([hero,foe]);
assert.equal(p.gearMaterials,0);
assert.equal(p.gear.kael.tier,1);
assert.deepEqual(Array.from(p.gear.kael.slots),[false,false,false,false,false,false]);
assert.equal(P.gearState(p,"enemy"),null);
assert.equal(P.canEquip(p,"kael",5),false,"no free equipment");
assert.equal(P.equip(p,"enemy",5),false,"enemies cannot equip");
assert.equal(P.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"}).material,12);
assert.equal(p.gearMaterials,12);
assert.equal(P.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"}),null,"first clear never repeats");
assert.equal(P.gearItem(1,0).currency,167);
assert.equal(P.gearItem(1,5).currency,166);
assert.equal(P.gearItem(1,5).name,"Амулет");
assert.equal(P.gearItem(1,5).atkBonus,.02);
assert.equal(P.gearItem(1,4).hpBonus,.02);
const start=P.heroStats(p,hero);
assert.equal(P.equip(p,"kael",5),true,"last slot can be installed first");
assert.equal(p.gear.kael.slots[5],true);
assert.equal(p.gear.kael.slots[0],false);
assert.equal(p.currency,334);
assert.equal(p.gearMaterials,10);
assert.equal(P.gearInstalled(p,"kael"),1);
assert.equal(P.heroStats(p,hero).hp,start.hp,"ATK slot does not boost HP");
assert.equal(P.gearBonuses(p,"kael").atk,.02,"ATK bonus recorded despite integer rounding");
assert.equal(P.heroStats(p,hero).atk,24,"small bonus rounds to integer ATK");
assert.equal(P.heroStats(p,hero).speed,110,"speed never changes");
assert.equal(P.equip(p,"kael",5),false,"no duplicate placement");
assert.match(P.gearBlockReason(p,"kael",5),/уже установлен/);
assert.equal(P.equip(p,"kael",0),true);
assert.equal(P.heroStats(p,hero).hp,122,"different slot grants HP");
p.currency=0;
assert.equal(P.equip(p,"kael",2),false,"insufficient currency");
p.currency=10000;
for(const i of [4,2,3,1])assert.equal(P.equip(p,"kael",i),true);
assert.equal(p.gear.kael.tier,2,"tier transition only after all six distinct slots");
assert.deepEqual(Array.from(p.gear.kael.slots),[false,false,false,false,false,false]);
assert.equal(P.gearInstalled(p,"kael"),6);
assert.equal(P.canEquip(p,"kael",0),false,"G2 requires level 6");
assert.match(P.gearBlockReason(p,"kael",0),/уровень героя 6/);
p.accountXp=100000;
p.levels.kael=6;p.gearMaterials=100;
const money=p.currency;
for(const i of [2,5,3,1,0,4])assert.equal(P.equip(p,"kael",i),true);
assert.equal(money-p.currency,2000,"G2 six-slot total cost");
assert.equal(p.gear.kael.tier,3);
assert.equal(P.canEquip(p,"kael",0),false,"G3 requires level 12");
p.levels.kael=12;
const before=p.currency;
for(const i of [1,3,5,0,2,4])assert.equal(P.equip(p,"kael",i),true);
assert.equal(before-p.currency,3000,"G3 six-slot total cost");
assert.equal(p.gear.kael.tier,3);
assert.equal(p.gear.kael.slots.filter(Boolean).length,6);
assert.equal(P.gearInstalled(p,"kael"),18);
assert.equal(P.gearCost(p,"kael",1),null);
assert.equal(P.equip(p,"kael",1),false);
assert.match(P.gearBlockReason(p,"kael",1),/уже установлен/);
assert.equal(P.heroStats(p,hero).speed,110);
assert.ok(Math.abs(P.gearBonuses(p,"kael").hp-.18)<1e-10);
assert.ok(Math.abs(P.gearBonuses(p,"kael").atk-.18)<1e-10);
const data=new Map(),storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)},get=()=>storage;
assert.equal(S.save(p,get),true);
const restored=S.load([hero,foe],get);
assert.equal(restored.fresh,false);
assert.equal(restored.progress.gear.kael.slots.filter(Boolean).length,6);
assert.equal(restored.progress.gearMaterials,p.gearMaterials);
assert.equal(restored.progress.currency,p.currency);
const legacy={version:2,accountXp:80,currency:400,levels:{kael:2},gearMaterials:4,
 gear:{kael:{tier:1,slots:2}},claimedMissions:["black-pass-ambush"]};
const migrated=S.validate(legacy,[hero,foe]);
assert.deepEqual(Array.from(migrated.gear.kael.slots),[true,true,false,false,false,false]);
assert.equal(migrated.currency,400);
assert.equal(migrated.gearMaterials,4);
assert.equal(P.gearInstalled(migrated,"kael"),2);
assert.equal(S.save(migrated,get),true);
const again=S.load([hero,foe],get);
assert.deepEqual(Array.from(again.progress.gear.kael.slots),[true,true,false,false,false,false]);
const advanced=S.validate({...legacy,accountXp:100000,levels:{kael:12},gear:{kael:{tier:3,slots:4}}},[hero,foe]);
assert.equal(P.gearInstalled(advanced,"kael"),16,"previous completed tiers preserved");
const partial=S.validate({...legacy,gear:{kael:{tier:1,slots:[false,true,false,true,false,false]}}},[hero,foe]);
assert.deepEqual(Array.from(partial.gear.kael.slots),[false,true,false,true,false,false]);
assert.equal(S.validate({...legacy,gear:{kael:{tier:1,slots:[false,true]}}},[hero,foe]),null);
assert.equal(S.validate({...legacy,gear:{kael:{tier:1,slots:[false,true,0,false,false,false]}}},[hero,foe]),null);
assert.equal(S.validate({...legacy,gear:{kael:{tier:1,slots:[true,true,true,true,true,true]}}},[hero,foe]),null);
assert.equal(S.validate({...legacy,gear:{kael:{tier:1,slots:7}}},[hero,foe]),null);
assert.equal(P.equip(p,"kael",NaN),false);
assert.equal(P.equip(p,"kael",-1),false);
assert.equal(P.equip(p,"kael",6),false);
console.log("Gear-002 independent slots, recipe costs, stats, level gates and legacy save migration passed");
