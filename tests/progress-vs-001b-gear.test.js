"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=["progress-core.js","save-core.js"].map(p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8")).join("\n");
const {ProgressCore:P,SaveCore:S}=vm.runInNewContext(source+"\n({ProgressCore,SaveCore})");
const hero={id:"kael",side:"ally",hp:120,atk:24,speed:110};
const foe={id:"enemy",side:"enemy",hp:90,atk:18,speed:99};
const p=P.createProgress([hero,foe]);
assert.equal(p.gearMaterials,0);
assert.equal(p.gear.kael.tier,1);
assert.equal(p.gear.kael.slots,0);
assert.equal(P.gearState(p,"enemy"),null);
assert.equal(P.canEquip(p,"kael"),false,"no free equipment");
assert.equal(P.equip(p,"enemy"),false,"enemies cannot equip");
assert.equal(P.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"}).material,12);
assert.equal(p.gearMaterials,12);
assert.equal(P.claimFirstClear(p,"black-pass-ambush",{active:false,winner:"ally"}),null,"no duplicate materials");
assert.equal(p.gearMaterials,12);
assert.equal(P.gearCost(p,"kael").currency,167);
const startStats=P.heroStats(p,hero);
assert.equal(P.canEquip(p,"kael"),true);
assert.equal(P.equip(p,"kael"),true);
assert.equal(p.gearMaterials,10);
assert.equal(p.currency,333);
assert.equal(P.gearInstalled(p,"kael"),1);
assert.equal(P.heroStats(p,hero).hp,121);
assert.equal(P.heroStats(p,hero).speed,startStats.speed,"equipment never raises speed");
assert.equal(P.equip(p,"kael"),true);
assert.equal(P.equip(p,"kael"),false,"insufficient currency blocks purchase");
p.currency=10000;
for(let i=0;i<4;i++)assert.equal(P.equip(p,"kael"),true);
assert.equal(P.gearInstalled(p,"kael"),6);
assert.equal(p.gear.kael.tier,2);
assert.equal(p.gear.kael.slots,0);
assert.equal(P.canEquip(p,"kael"),false,"G2 requires level 6");
assert.match(P.gearBlockReason(p,"kael"),/уровень героя 6/);
p.accountXp=100000;
p.levels.kael=6;
p.gearMaterials=100;
assert.equal(P.gearCost(p,"kael").material,3);
const money=p.currency;
for(let i=0;i<6;i++)assert.equal(P.equip(p,"kael"),true);
assert.equal(money-p.currency,2000);
assert.equal(p.gear.kael.tier,3);
assert.equal(p.gear.kael.slots,0);
assert.match(P.gearBlockReason(p,"kael"),/уровень героя 12/);
p.levels.kael=12;
const before=p.currency;
for(let i=0;i<6;i++)assert.equal(P.equip(p,"kael"),true);
assert.equal(before-p.currency,3000);
assert.equal(p.gear.kael.tier,3);
assert.equal(p.gear.kael.slots,6);
assert.equal(P.gearInstalled(p,"kael"),18);
assert.equal(P.gearCost(p,"kael"),null);
assert.equal(P.equip(p,"kael"),false);
assert.match(P.gearBlockReason(p,"kael"),/Все слоты/);
assert.equal(P.heroStats(p,hero).speed,110);
const storageMap=new Map(),storage={
 getItem:k=>storageMap.get(k)??null,setItem:(k,v)=>storageMap.set(k,v)
};
const get=()=>storage;
assert.equal(S.save(p,get),true);
const restored=S.load([hero,foe],get);
assert.equal(restored.fresh,false);
assert.equal(restored.progress.gear.kael.slots,6);
assert.equal(restored.progress.gearMaterials,p.gearMaterials);
assert.equal(restored.progress.currency,p.currency);
// Existing VS-001A saves are compatible and receive empty gear without resetting levels/rewards.
const old={version:2,accountXp:80,currency:400,levels:{kael:2},claimedMissions:["black-pass-ambush"]};
const migrated=S.validate(old,[hero,foe]);
assert.equal(migrated.levels.kael,2);
assert.equal(migrated.currency,400);
assert.equal(migrated.gearMaterials,0);
assert.equal(migrated.gear.kael.tier,1);
assert.equal(migrated.gear.kael.slots,0);
assert.equal(S.validate({...old,gear:{kael:{tier:3,slots:6}}},[hero,foe]),null,"no high gear on underlevelled hero");
assert.equal(S.validate({...old,gearMaterials:-1},[hero,foe]),null);
assert.equal(S.validate({...old,gear:{kael:{tier:1,slots:7}}},[hero,foe]),null);
assert.equal(S.validate({...old,gear:{kael:{tier:1,slots:6}}},[hero,foe]),null);
console.log("VS-001B gear recipes, gates, combat scaling, rewards, v2 persistence passed");
