"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const src=["progress-core.js","save-core.js"].map(x=>fs.readFileSync(path.join(__dirname,"..",x),"utf8")).join("\n");
const {ProgressCore:P,SaveCore:S}=vm.runInNewContext(src+"\n({ProgressCore,SaveCore})");
const hero={id:"kael",side:"ally",hp:120,atk:24,speed:110};
const p=P.createProgress([hero]),start=1_000_000;
p.energy=P.freshEnergy(start);
assert.equal(p.energy.value,240);
assert.equal(P.missionEnergyCost("black-pass-ambush"),10);
assert.equal(P.missionEnergyCost("demo-mission-2"),12);
assert.equal(P.missionEnergyCost("demo-mission-3"),16);
assert.equal(P.missionEnergyCost("invalid"),null);
assert.equal(P.simulate(p,"black-pass-ambush",0,1,start),null,"3 stars required");
assert.equal(P.simulate(p,"invalid",3,1,start),null);
assert.equal(P.simulate(p,"black-pass-ambush",3,0,start),null,"zero runs forbidden");
assert.equal(P.simulate(p,"black-pass-ambush",3,1.5,start),null);
assert.equal(P.simulate(p,"black-pass-ambush",3,25,start),null,"max limited by energy");
assert.equal(P.affordableRuns(p,"black-pass-ambush",start),24);
const batch=P.simulate(p,"black-pass-ambush",3,3,start+1);
assert.equal(batch.count,3);
assert.equal(batch.energy,30);
assert.equal(batch.material,36);
assert.equal(batch.xp,15);
assert.equal(p.gearMaterials,36);
assert.equal(p.energy.value,210);
assert.equal(p.energy.updatedAt,start+1);
assert.equal(P.refreshEnergy(p,start+360_000),0);
assert.equal(P.refreshEnergy(p,start+360_001),1);
assert.equal(p.energy.value,211);
assert.equal(P.spendEnergy(p,"demo-mission-2",1,start+360_002),true,"manual mission uses same energy");
assert.equal(p.energy.value,199);
assert.equal(p.energy.updatedAt,start+360_001,"partial energy time remains");
assert.equal(P.refundEnergy(p,"demo-mission-2",start+360_003),true,"failed battle start can refund");
assert.equal(p.energy.value,211);
const second=P.simulate(p,"demo-mission-2",3,2,start+360_003);
assert.equal(second.energy,24);
assert.equal(second.currency,400);
assert.equal(second.xp,10);
assert.equal(p.currency,400);
assert.equal(p.accountXp,25);
const third=P.simulate(p,"demo-mission-3",3,2,start+360_004);
assert.equal(third.energy,32);
assert.equal(third.material,48);
assert.equal(p.gearMaterials,84);
p.energy={value:9,updatedAt:start};
assert.equal(P.spendEnergy(p,"black-pass-ambush",1,start),false);
assert.equal(P.simulate(p,"black-pass-ambush",3,1,start),null);
assert.equal(P.affordableRuns(p,"black-pass-ambush",start),0);
assert.equal(P.refreshEnergy(p,start+360_000),1);
assert.equal(P.spendEnergy(p,"black-pass-ambush",1,start+360_000),true);
assert.equal(p.energy.value,0);
p.energy={value:1,updatedAt:start};
assert.equal(P.refreshEnergy(p,start+360_000*1000),239,"offline regeneration capped");
assert.equal(p.energy.value,240);
assert.equal(P.refreshEnergy(p,start-1),0,"backwards clock");
const store=new Map(),storage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)};
assert.equal(S.save(p,()=>storage),true);
const reloaded=S.load([hero],()=>storage);
assert.equal(reloaded.fresh,false);
assert.equal(reloaded.progress.energy.value,240);
assert.equal(reloaded.progress.currency,400);
assert.equal(reloaded.progress.gearMaterials,84);
assert.equal(reloaded.progress.accountXp,35);
const legacy={version:2,accountXp:80,currency:100,gearMaterials:3,levels:{kael:2},
 gear:{kael:{tier:1,slots:1}},claimedMissions:["black-pass-ambush"]};
const restored=S.validate(legacy,[hero]);
assert.equal(restored.levels.kael,2);
assert.equal(restored.currency,100);
assert.equal(restored.energy.value,240);
assert.equal(S.validate({...legacy,energy:{value:241,updatedAt:start}},[hero]),null);
console.log("SIM001 mission energy, batch reward, safety gates, offline regen and saves passed");
