"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const src=["progress-core.js","save-core.js"].map(x=>fs.readFileSync(path.join(__dirname,"..",x),"utf8")).join("\n");
const {ProgressCore:P,SaveCore:S}=vm.runInNewContext(src+"\n({ProgressCore,SaveCore})");
const hero={id:"kael",side:"ally",hp:120,atk:24,speed:110};
const p=P.createProgress([hero]);
const start=1_000_000;
p.energy=P.freshEnergy(start);
assert.equal(p.energy.value,240);
assert.equal(P.farm(p,P.FARM_MISSION_ID,0,"materials",start),null,"locked without 3 stars");
assert.equal(P.farm(p,"demo-mission-2",3,"materials",start),null,"wrong source");
assert.equal(P.farm(p,P.FARM_MISSION_ID,3,"unknown",start),null,"unknown resource");
assert.equal(P.farm(p,P.FARM_MISSION_ID,3,"materials",start+1).material,12);
assert.equal(p.energy.value,230);
assert.equal(p.energy.updatedAt,start+1,"regen starts at spend when previously capped");
assert.equal(p.gearMaterials,12);
assert.equal(p.accountXp,5);
assert.equal(P.refreshEnergy(p,start+1+359_999),0);
assert.equal(P.refreshEnergy(p,start+1+360_000),1);
assert.equal(p.energy.value,231);
assert.equal(P.farm(p,P.FARM_MISSION_ID,3,"currency",start+1+360_001).currency,200);
assert.equal(p.energy.value,221);
assert.equal(p.currency,200);
assert.equal(p.accountXp,10);
assert.equal(p.energy.updatedAt,start+1+360_000,"spending below cap preserves partial time");
p.energy={value:0,updatedAt:start};
assert.equal(P.farm(p,P.FARM_MISSION_ID,3,"materials",start),null,"cannot overdraft");
assert.equal(P.refreshEnergy(p,start+360_000*9),9);
assert.equal(p.energy.value,9);
assert.equal(P.canFarm(p,P.FARM_MISSION_ID,3,"materials",start+360_000*9),false);
assert.equal(P.refreshEnergy(p,start+360_000*10),1);
assert.equal(P.canFarm(p,P.FARM_MISSION_ID,3,"materials",start+360_000*10),true);
assert.equal(P.farm(p,P.FARM_MISSION_ID,3,"materials",start+360_000*10).xp,5);
assert.equal(p.energy.value,0);
p.energy={value:1,updatedAt:start};
assert.equal(P.refreshEnergy(p,start+360_000*1000),239,"offline refill capped");
assert.equal(p.energy.value,240);
assert.equal(p.energy.updatedAt,start+360_000*1000);
assert.equal(P.refreshEnergy(p,start-1),0,"clock backwards cannot grant energy");
const map=new Map(),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
assert.equal(S.save(p,()=>storage),true);
const reload=S.load([hero],()=>storage);
assert.equal(reload.fresh,false);
assert.equal(reload.progress.energy.value,240);
assert.equal(reload.progress.energy.updatedAt,p.energy.updatedAt);
assert.equal(reload.progress.gearMaterials,p.gearMaterials);
assert.equal(reload.progress.currency,200);
assert.equal(reload.progress.accountXp,15);
// Older progress.v2 saved before energy was introduced remains valid.
const legacy={version:2,accountXp:80,currency:100,gearMaterials:3,levels:{kael:2},
 gear:{kael:{tier:1,slots:1}},claimedMissions:["black-pass-ambush"]};
const restored=S.validate(legacy,[hero]);
assert.equal(restored.levels.kael,2);
assert.equal(restored.gear.kael.slots,1);
assert.equal(restored.currency,100);
assert.equal(restored.energy.value,240);
assert.equal(S.validate({...legacy,energy:{value:241,updatedAt:start}},[hero]),null);
assert.equal(S.validate({...legacy,energy:{value:2,updatedAt:-1}},[hero]),null);
assert.equal(S.validate({...legacy,energy:{value:0.5,updatedAt:start}},[hero]),null);
console.log("Progress VS-001C energy, offline regeneration, farm gates and v2 saves passed");
