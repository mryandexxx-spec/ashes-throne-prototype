"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const root=path.join(__dirname,"..");
const source=["progress-core.js","save-core.js"].map(f=>fs.readFileSync(path.join(root,f),"utf8")).join("\n");
const {ProgressCore,SaveCore}=vm.runInNewContext(source+"\n({ProgressCore,SaveCore})");
const heroes=[{id:"kael",side:"ally"},{id:"lyra",side:"ally"},{id:"darin",side:"ally"},{id:"ves",side:"enemy"}];
const map=new Map();
const storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v)};
const get=()=>storage;
let result=SaveCore.load(heroes,get);
assert.equal(result.available,true);
assert.equal(result.progress.materials,0);
assert.equal(result.progress.levels.kael,1);
result.progress.materials=4;
result.progress.levels.kael=2;
assert.equal(SaveCore.save(result.progress,get),true);
const restored=SaveCore.load(heroes,get);
assert.equal(restored.progress.materials,4);
assert.equal(restored.progress.levels.kael,2);
assert.equal(restored.progress.levels.lyra,1);
assert.equal(map.size,1,"only one versioned progress record");
function invalid(data){
 map.set(SaveCore.KEY,typeof data==="string"?data:JSON.stringify(data));
 const value=SaveCore.load(heroes,get);
 assert.equal(value.progress.materials,0);
 assert.equal(value.progress.levels.kael,1);
}
invalid("{broken json");
invalid({version:999,materials:9,levels:{kael:3,lyra:3,darin:3}});
invalid({version:1,materials:-1,levels:{kael:2,lyra:1,darin:1}});
invalid({version:1,materials:1.5,levels:{kael:2,lyra:1,darin:1}});
invalid({version:1,materials:5,levels:{kael:4,lyra:1,darin:1}});
invalid({version:1,materials:5,levels:{kael:2,lyra:1}});
invalid({version:1,materials:5,levels:{kael:2,lyra:1,darin:1,unknown:1}});
invalid({version:1,materials:5,levels:[]});
assert.equal(SaveCore.load(heroes,()=>{throw Error("blocked");}).available,false);
assert.equal(SaveCore.load(heroes,()=>({getItem(){throw Error("blocked");}})).progress.materials,0);
assert.equal(SaveCore.save(restored.progress,()=>({setItem(){throw Error("quota");}})),false);
assert.equal(SaveCore.save(restored.progress,()=>{throw Error("denied");}),false);
console.log("Save-001 versioning, validation, persistence and Safari storage failures passed");
