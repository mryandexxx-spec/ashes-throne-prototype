"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const src=["progress-core.js","save-core.js"].map(f=>fs.readFileSync(path.join(__dirname,"..",f),"utf8")).join("\n");
const {ProgressCore,SaveCore}=vm.runInNewContext(src+"\n({ProgressCore,SaveCore})");
const heroes=[{id:"kael",side:"ally"},{id:"lyra",side:"ally"},{id:"darin",side:"ally"},{id:"ves",side:"enemy"}];
const map=new Map();
const storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v)};
const get=()=>storage;
assert.equal(SaveCore.KEY,"ashes-throne.progress.v2");
map.set("ashes-throne.progress.v1",JSON.stringify({version:1,materials:50,levels:{kael:3,lyra:3,darin:3}}));
let result=SaveCore.load(heroes,get);
assert.equal(result.available,true);
assert.equal(result.fresh,true,"old progress does not count as new economy save");
assert.equal(result.progress.currency,0,"old demo economy is intentionally reset");
assert.equal(result.progress.levels.kael,1);
assert.equal(result.progress.accountXp,0);
assert.equal(ProgressCore.claimFirstClear(result.progress,"black-pass-ambush",{active:false,winner:"ally"}).xp,80);
assert.equal(ProgressCore.upgrade(result.progress,"kael"),true);
assert.equal(SaveCore.save(result.progress,get),true);
const restored=SaveCore.load(heroes,get);
assert.equal(restored.fresh,false,"saved v2 economy reloads without reset");
assert.equal(restored.progress.currency,461);
assert.equal(restored.progress.accountXp,80);
assert.equal(restored.progress.levels.kael,2);
assert.equal(restored.progress.levels.lyra,1);
assert.deepEqual(Array.from(restored.progress.claimedMissions),["black-pass-ambush"]);
assert.equal(ProgressCore.claimFirstClear(restored.progress,"black-pass-ambush",{active:false,winner:"ally"}),null);
function invalid(data){
 map.set(SaveCore.KEY,typeof data==="string"?data:JSON.stringify(data));
 const value=SaveCore.load(heroes,get);
 assert.equal(value.progress.currency,0);
 assert.equal(value.progress.levels.kael,1);
}
invalid("{bad");
invalid({version:1,currency:20,accountXp:80,levels:{kael:1,lyra:1,darin:1},claimedMissions:[]});
invalid({version:2,currency:-1,accountXp:80,levels:{kael:1,lyra:1,darin:1},claimedMissions:[]});
invalid({version:2,currency:0,accountXp:-1,levels:{kael:1,lyra:1,darin:1},claimedMissions:[]});
invalid({version:2,currency:0,accountXp:0,levels:{kael:3,lyra:1,darin:1},claimedMissions:[]});
invalid({version:2,currency:0,accountXp:0,levels:{kael:1,lyra:1,darin:1},claimedMissions:["black-pass-ambush","black-pass-ambush"]});
invalid({version:2,currency:0,accountXp:0,levels:{kael:1,lyra:1,darin:1},claimedMissions:["unknown"]});
invalid({version:2,currency:0,accountXp:0,levels:{kael:1,lyra:1,darin:1,enemy:1},claimedMissions:[]});
assert.equal(SaveCore.load(heroes,()=>{throw Error("blocked");}).available,false);
assert.equal(SaveCore.load(heroes,()=>({getItem(){throw Error("blocked");}})).progress.currency,0);
assert.equal(SaveCore.save(restored.progress,()=>({setItem(){throw Error("quota");}})),false);
console.log("Progress VS-001A new v2 save, intentional reset, validation, failures passed");
