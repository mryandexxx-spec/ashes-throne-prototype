"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.join(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
const {StoryDemoCore}=vm.runInNewContext(read("story-demo-core.js")+"\n({StoryDemoCore})");
const start=StoryDemoCore.fresh();
assert.equal(start.phase,"intro");
assert.match(StoryDemoCore.view(start).text,/ущелья/);
assert.equal(StoryDemoCore.startBattle(start),false,"cannot skip into combat");
for(let i=0;i<StoryDemoCore.beats.length;i++)assert.equal(StoryDemoCore.next(start),true);
assert.equal(start.phase,"tone");
assert.equal(StoryDemoCore.chooseTone(start,"bogus"),false);
assert.equal(StoryDemoCore.chooseTone(start,"people"),true);
assert.match(StoryDemoCore.view(start).text,/Спасатели/);
assert.equal(StoryDemoCore.startBattle(start),true);
assert.equal(StoryDemoCore.chooseEvidence(start,"warn"),false,"cannot choose after combat starts");
assert.equal(StoryDemoCore.cancelBattle(start),true,"squad back restores story intro");
assert.equal(start.phase,"ready");
assert.equal(StoryDemoCore.startBattle(start),true);
assert.equal(StoryDemoCore.finishBattle(start,true),true);
assert.equal(start.phase,"evidence");
assert.equal(StoryDemoCore.finishBattle(start,true),false,"result is idempotent");
assert.equal(StoryDemoCore.chooseEvidence(start,"verify"),true);
assert.match(StoryDemoCore.view(start).text,/Нада сверяет/);
assert.equal(start.phase,"ending");
assert.equal(StoryDemoCore.next(start),false);
const loss=StoryDemoCore.fresh();
while(loss.phase==="intro")StoryDemoCore.next(loss);
StoryDemoCore.chooseTone(loss,"order");StoryDemoCore.startBattle(loss);
StoryDemoCore.finishBattle(loss,false);
assert.equal(loss.phase,"defeat");
const warn=StoryDemoCore.fresh();
while(warn.phase==="intro")StoryDemoCore.next(warn);
StoryDemoCore.chooseTone(warn,"order");StoryDemoCore.startBattle(warn);
StoryDemoCore.finishBattle(warn,true);StoryDemoCore.chooseEvidence(warn,"warn");
assert.match(StoryDemoCore.view(warn).text,/не проверено/);
const html=read("index.html"),game=read("game.js");
assert.match(html,/id="storyDemoOpen"/);
assert.match(html,/id="storyDemoChoices"/);
assert.match(html,/src="story-demo-core.js"/);
assert.match(game,/battleIsStoryDemo&&!state.active&&!missionResultShown/);
assert.match(game,/StoryDemoCore.finishBattle/);
assert.match(game,/openSquad\("storyDemo"\)/);
assert.match(html,/v0\.3\.92 · UIHERO001/);
assert.equal(StoryDemoCore.fresh().phase,"intro","no persisted story state");
console.log("STORY-001: narrative flow, guards, retry, and integration wiring checked");
