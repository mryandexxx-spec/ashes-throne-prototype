#!/usr/bin/env node
/* ASSETLOAD001: regenerates asset-manifest.js from the real files.
 * Run after any GLB/arena image changes: node tools/build-asset-manifest.cjs
 * Size and sha256 come from disk; names from the game's own catalogs. */
"use strict";
const fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto");
const root=path.join(__dirname,"..");
const NpcModelAssets=require(path.join(root,"dev/src/assets/npc-models.js"));
const NpcEnemyData=require(path.join(root,"npc-enemy-data.js"));
const list=[
 ["hero:ren","hero","Рен","assets/ren-meshy-mixamo-animated.glb"],
 ["hero:nada","hero","Нада","dev/assets/models/nada-mobile-animated.glb"],
 ["hero:liora","hero","Лиора","dev/assets/models/liora-mobile-animated.glb"],
 ["hero:sava","hero","Сава","dev/assets/models/sava-mobile-animated.glb"],
 ["hero:art","hero","Арт","dev/assets/models/art-mobile-animated.glb"],
 ...Object.values(NpcModelAssets.models).map(m=>["npc:"+m.id,"enemy",NpcEnemyData.get(m.id)?.name||m.id,m.url]),
 ["arena:env005","arena","Фон арены","assets/arena-env005-terrace.webp"],
 ["arena:env006","arena","3D-арена","assets/arena-env006-terrace-projection.webp"],
 ["arena:env006b","arena","Анимация арены","assets/arena-env006b-anim-mask.webp"]
];
const rows=list.map(([id,kind,label,url])=>{
 const buf=fs.readFileSync(path.join(root,url));
 const rev=crypto.createHash("sha256").update(buf).digest("hex").slice(0,8);
 return ` Object.freeze({id:${JSON.stringify(id)},kind:${JSON.stringify(kind)},label:${JSON.stringify(label)},url:${JSON.stringify(url)},bytes:${buf.length},rev:${JSON.stringify(rev)}})`;
});
const out=`/* ASSETLOAD001 — the one list of heavy game assets (3D models and arena art).
 * GENERATED by tools/build-asset-manifest.cjs; do not edit by hand.
 * Used by the page (one loading bar), by the service worker (device cache) and by tests.
 * rev = first 8 hex of sha256: a changed file gets a new cache key, never stale bytes. */
const AssetManifest=(()=>{
 "use strict";
 const ASSETS=Object.freeze([
${rows.join(",\n")}
 ]);
 const byId=new Map(ASSETS.map(a=>[a.id,a]));
 const byPath=new Map(ASSETS.map(a=>[a.url,a]));
 // Short, stable revision of the whole set (FNV-1a over id+rev).
 let h=0x811c9dc5;
 for(const ch of ASSETS.map(a=>a.id+"@"+a.rev).join("|")){h^=ch.charCodeAt(0);h=Math.imul(h,0x01000193)>>>0;}
 const REVISION=h.toString(16).padStart(8,"0");
 const get=id=>byId.get(id)||null;
 const forPath=p=>byPath.get(String(p||"").replace(/^\\.?\\//,""))||null;
 const totalBytes=ids=>(ids||ASSETS.map(a=>a.id)).reduce((s,id)=>s+(byId.get(id)?.bytes||0),0);
 return Object.freeze({ASSETS,REVISION,get,forPath,totalBytes});
})();
if(typeof module!=="undefined"&&module.exports)module.exports=AssetManifest;
`;
fs.writeFileSync(path.join(root,"asset-manifest.js"),out);
console.log("asset-manifest.js:",list.length,"assets");
